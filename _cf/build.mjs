// Workers Builds build step for similarize.com (run from repo root: `node _cf/build.mjs`).
// 1) Reproduce the only Jekyll transform the site relies on: strip YAML front matter from
//    HTML files that start with "---" (index.html has `layout: null` and no Liquid).
// 2) Workers Static Assets rejects files over 25 MiB. Split each such file into parts under
//    cf-parts/, ignore the original in .assetsignore, and write _cf/bigfiles.json so
//    _cf/worker.js can stream the parts back together at the original URL.
// Safe to re-run; it only edits the build checkout.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const LIMIT = 25 * 1024 * 1024;
const PART = 20 * 1024 * 1024;
const PARTS_DIR = "cf-parts";
const TYPES = { ".wasm": "application/wasm", ".data": "application/octet-stream", ".apk": "application/vnd.android.package-archive",
  ".mp4": "video/mp4", ".webm": "video/webm", ".zip": "application/zip", ".js": "application/javascript; charset=utf-8",
  ".bin": "application/octet-stream", ".glb": "model/gltf-binary", ".ogg": "audio/ogg", ".mp3": "audio/mpeg", ".wav": "audio/wav" };

// Same skip rules as .assetsignore / Jekyll: any segment starting with "_" or ".", plus build dirs.
const skip = (rel) => rel.split("/").some((s) => s.startsWith("_") || s.startsWith(".")) ||
  ["node_modules", PARTS_DIR, "Gemfile", "Gemfile.lock", "wrangler.jsonc"].includes(rel.split("/")[0]);

function* walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name);
    const rel = path.relative(ROOT, abs).split(path.sep).join("/");
    if (skip(rel)) continue;
    if (e.isDirectory()) yield* walk(abs);
    else if (e.isFile()) yield { abs, rel };
  }
}

let stripped = 0;
const big = {};
fs.rmSync(path.join(ROOT, PARTS_DIR), { recursive: true, force: true });
for (const { abs, rel } of walk(ROOT)) {
  const size = fs.statSync(abs).size;
  if (/\.html?$/i.test(rel) && size < LIMIT) {
    const txt = fs.readFileSync(abs, "utf8");
    const m = txt.match(/^---\r?\n[\s\S]*?\r?\n---[ \t]*\r?\n/);
    if (m) {
      if (/\{\{|\{%/.test(txt)) console.warn(`WARN ${rel}: has Liquid tags; Jekyll would render them, this build does not`);
      fs.writeFileSync(abs, txt.slice(m[0].length));
      stripped++;
    }
  }
  if (size > LIMIT) {
    const fd = fs.openSync(abs, "r");
    const parts = [];
    for (let off = 0, i = 0; off < size; off += PART, i++) {
      const len = Math.min(PART, size - off);
      const buf = Buffer.alloc(len);
      fs.readSync(fd, buf, 0, len, off);
      const partRel = `${PARTS_DIR}/${rel}.part${i}`;
      fs.mkdirSync(path.dirname(path.join(ROOT, partRel)), { recursive: true });
      fs.writeFileSync(path.join(ROOT, partRel), buf);
      parts.push("/" + partRel.split("/").map(encodeURIComponent).join("/"));
    }
    fs.closeSync(fd);
    const key = "/" + rel.split("/").map(encodeURIComponent).join("/");
    big[key] = { size, type: TYPES[path.extname(rel).toLowerCase()] || "application/octet-stream", parts };
    console.log(`split ${rel} (${(size / 1048576).toFixed(1)} MiB) into ${parts.length} parts`);
  }
}

fs.writeFileSync(path.join(ROOT, "_cf/bigfiles.json"), JSON.stringify(big, null, 1) + "\n");

const IGN = path.join(ROOT, ".assetsignore");
const ign = fs.readFileSync(IGN, "utf8");
const START = "# >>> generated by _cf/build.mjs", END = "# <<< generated";
const a = ign.indexOf(START), b = ign.indexOf(END);
const block = `${START} (files over 25 MiB; served from cf-parts/ by _cf/worker.js)\n` +
  Object.keys(big).map((k) => "/" + decodeURIComponent(k.slice(1)).replace(/([*?\[\]!#\\ ])/g, "\\$1")).join("\n") + (Object.keys(big).length ? "\n" : "") + END;
const out = a >= 0 && b > a ? ign.slice(0, a) + block + ign.slice(b + END.length) : ign + "\n" + block + "\n";
fs.writeFileSync(IGN, out);
console.log(`front matter stripped from ${stripped} file(s); ${Object.keys(big).length} big file(s) split`);
